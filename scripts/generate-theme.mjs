// Generates the Material 3 color scheme (light + dark) from the brand seed color.
// Output is a static file so the app ships no color math. Usage: npm run theme
import {
  argbFromHex,
  Blend,
  hexFromArgb,
  Hct,
  MaterialDynamicColors,
  SchemeContent,
  TonalPalette,
} from '@material/material-color-utilities';
import { writeFileSync } from 'node:fs';

const SEED = '#10A66B';
const OWE = '#F2690D'; // "you owe" accent, harmonized toward the seed

const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow', 'surfaceContainer',
  'surfaceContainerHigh', 'surfaceContainerHighest',
  'outline', 'outlineVariant', 'shadow', 'scrim', 'inverseSurface', 'inverseOnSurface', 'inversePrimary',
];

function scheme(isDark) {
  const s = new SchemeContent(Hct.fromInt(argbFromHex(SEED)), isDark, 0);
  const out = {};
  for (const role of ROLES) out[role] = hexFromArgb(MaterialDynamicColors[role].getArgb(s));

  // Text tones keep the full color; containers use a calmer chroma, as Material does for containers.
  const owedHct = Hct.fromInt(argbFromHex(SEED));
  const oweHct = Hct.fromInt(Blend.harmonize(argbFromHex(OWE), argbFromHex(SEED)));
  const owed = TonalPalette.fromInt(argbFromHex(SEED));
  const owe = TonalPalette.fromInt(oweHct.toInt());
  const owedSoft = TonalPalette.fromHueAndChroma(owedHct.hue, 22);
  const oweSoft = TonalPalette.fromHueAndChroma(oweHct.hue, 26);
  Object.assign(out, {
    owed: hexFromArgb(owed.tone(isDark ? 80 : 40)),
    owedContainer: hexFromArgb(owedSoft.tone(isDark ? 25 : 92)),
    onOwedContainer: hexFromArgb(owedSoft.tone(isDark ? 92 : 10)),
    owe: hexFromArgb(owe.tone(isDark ? 80 : 45)),
    oweContainer: hexFromArgb(oweSoft.tone(isDark ? 25 : 92)),
    onOweContainer: hexFromArgb(oweSoft.tone(isDark ? 92 : 10)),
  });
  return out;
}

const body = (o) => Object.entries(o).map(([k, v]) => `  ${k}: '${v}',`).join('\n');
const file = `// Generated by scripts/generate-theme.mjs from seed ${SEED}. Do not edit by hand.

export const lightColors = {
${body(scheme(false))}
};

export const darkColors: typeof lightColors = {
${body(scheme(true))}
};

export type SchemeColors = typeof lightColors;
`;
writeFileSync('src/theme/palette.ts', file);
console.log('✓ src/theme/palette.ts');
